; Комплексная тестовая программа для УВМ
; Демонстрация всех команд с поддержкой hex

; Инициализация данных
[1000] = 4660        ; 0x1234 в десятичном виде
; Или с поддержкой hex в новом парсере:
; [1000] = 0x1234     ; Шестнадцатеричное значение

[1001] = 1000        ; Указатель на значение
[1002] = 5           ; Смещение
[1003] = 0           ; Результат

; Основная программа

; 1. Загрузка константы в память
[200] = 42
[201] = -15          ; Отрицательная константа

; 2. Копирование значения через указатель
;    [202] = значение по адресу 1000
[202] = [[1001] + 0]

; 3. Запись с использованием смещения
;    Записываем значение из [200] по адресу [1001] + 2
[[1001] + 2] = [200]

; 4. Чтение с использованием смещения
;    [203] = значение по адресу [1001] + 2
[203] = [[1001] + 2]

; 5. Обращение битов
;    [204] = bitreverse(значение из [1000])
[204] = bitreverse([1000])

; 6. Создание цепочки операций
[205] = 255          ; 0x00FF в десятичном виде
[206] = bitreverse([205])  ; Обращенная маска = 0xFF00

; 8. Дополнительные операции с памятью
[300] = 10
[301] = [[300] + 0]  ; Чтение из адреса 10
[[300] + 1] = [301]  ; Запись по адресу 11